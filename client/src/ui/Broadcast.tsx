// Broadcast feed: the overlay cues as they're emitted, plus downloads of the cue sheet.

import type { OverlayCue } from '@ghost/engine';
import { useMatch } from '../store';
import { downloadJSON } from './format';

type P = Record<string, unknown> & { slot?: string; clock?: string };

/** One readable line per cue. */
export function cueSummary(c: OverlayCue): string {
  const p = c.payload as P;
  switch (c.kind) {
    case 'milestone':
      return `${p.label}${p.scorerName ? ` · ${p.scorerName}` : ''}${p.score ? ` · ${(p.score as { home: number; away: number }).home}-${(p.score as { home: number; away: number }).away}` : ''}`;
    case 'stat':
      return p.label === 'Shot' ? `Shot · ${p.name} · xG ${p.xG ?? '–'}${p.speedKmh ? ` · ${p.speedKmh} km/h` : ''}` : p.label === 'Match stats' ? `Match stats · possession ${(p.possession as { home: number }).home}%` : `${p.label} · ${p.name ?? ''} ${p.difficulty ? `${p.difficulty}/10` : ''}`;
    case 'ghost_replay':
      return `Ghost replay · ${p.name} · value lost ${p.valueLost}`;
    case 'player_tag':
      return `Tag · ${p.shortName} (${p.tag})`;
    case 'narrative':
      return `${String(p.text).slice(0, 70)}${String(p.text).length > 70 ? '…' : ''}`;
    default:
      return c.kind;
  }
}

/** The cue sheet in the same shape the server's /api/cues returns. */
export function cueSheet(cues: OverlayCue[]) {
  const meta = useMatch.getState().meta!;
  const team = (s: 'home' | 'away') => ({ id: meta[s].id, name: meta[s].name, shortName: meta[s].shortName, colors: meta[s].colors });
  return {
    format: 'ghost-replay.overlay-cues',
    version: 1,
    matchId: meta.matchId,
    teams: { home: team('home'), away: team('away') },
    timebase: 'startT/durationMs in ms since kick-off, continuous across halves (the half-time break is excluded); payload.clock is the match clock as displayed',
    coordinates: 'metres on a 105 x 68 pitch, origin bottom-left, home attacking left to right',
    generatedAt: new Date().toISOString(),
    cues: [...cues].sort((a, b) => a.startT - b.startT),
  };
}

export async function downloadFullCueSheet() {
  const { matchParams, meta } = useMatch.getState();
  if (!matchParams || !meta) return;
  const q = new URLSearchParams({ seed: String(matchParams.seed), home: meta.home.id, away: meta.away.id });
  const res = await fetch(`/api/cues?${q}`);
  downloadJSON(`${meta.matchId}-cues-full.json`, await res.json());
}

export function BroadcastTab() {
  const cues = useMatch((s) => s.cues);
  const meta = useMatch((s) => s.meta);
  if (!meta) return null;
  const latest = cues.slice(-12).reverse();
  return (
    <>
      <p className="feed-intro">
        Timed, machine-readable overlay cues a broadcaster can sync to their feed: milestones, ghost replays, player tags, stats and commentary. Click a cue to see its JSON.
      </p>
      <div className="btn-row">
        <button className="btn-ai" onClick={downloadFullCueSheet} title="The whole match's cue sheet, generated by the server">
          Full match cue sheet
        </button>
        <button disabled={!cues.length} onClick={() => downloadJSON(`${meta.matchId}-cues-so-far.json`, cueSheet(cues))}>
          Cues so far <span className="mono">{cues.length}</span>
        </button>
      </div>
      {latest.length === 0 && <div className="empty">Cues appear here as the match plays.</div>}
      <div>
        {latest.map((c) => {
          const p = c.payload as P;
          return (
            <details key={c.cueId} className="cue">
              <summary>
                <span className="tl-min">{p.clock}</span>
                <span className={`cue-kind cue-${c.kind}`}>{c.kind.replace('_', ' ')}</span>
                <span className="cue-text">{cueSummary(c)}</span>
              </summary>
              <pre>{JSON.stringify(c, null, 1).slice(0, 1500)}</pre>
            </details>
          );
        })}
      </div>
    </>
  );
}
