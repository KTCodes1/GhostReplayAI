// Usage: npm run validate   (writes docs/VALIDATION.md)
//
// Reproducible validation on held-out matches (seeds never used while tuning the models):
//   1. Calibration — do predicted chances match observed rates? (pass completion in the simulated
//      world; the reactive simulation against the model)
//   2. Counterfactual robustness — change one thing (a defender closer, a defender in the lane,
//      slower defenders) and check the numbers move the way football says they should.
//   3. Explanation correctness — feed the evidence checker deliberately false claims and measure
//      how many it rejects, and confirm the fact-built explanations always pass.
//   4. The simulation check — how often the 50-run simulation upholds a moment the model flagged.
// Every number here is measured by this script. Note: the matches are synthetic, so calibration
// shows the engine is consistent with its simulated world, not that it matches real football.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  type DecisionMoment,
  type GeneratedMatch,
  type GhostAnalysis,
  type GhostOption,
  type MatchEvent,
  type MatchMeta,
  analyzeEvent,
  analyzeMatch,
  buildRoster,
  checkAgainstFacts,
  dist,
  generateMatch,
  momentFacts,
  numbersIn,
  simulateWhatIf,
  templateExplanation,
} from '../src/index';

const SEEDS = [101, 102, 103, 104, 105, 106, 107, 108];
const OUT = fileURLToPath(new URL('../../docs/VALIDATION.md', import.meta.url));
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const lines: string[] = [];
const log = (s = '') => {
  lines.push(s);
  console.log(s);
};
const t0 = performance.now();

type Ctx = { match: GeneratedMatch; analyses: GhostAnalysis[]; live: DecisionMoment[]; recap: DecisionMoment[]; prev: Map<string, MatchEvent | undefined>; agreement: { checked: number; agreed: number } };
const ctxs: Ctx[] = SEEDS.map((seed) => {
  const match = generateMatch({ seed });
  const { live, recap, detector } = analyzeMatch(match);
  const prev = new Map(match.events.map((e, i) => [e.id, match.events[i - 1]]));
  return { match, analyses: [...detector.analyses()], live, recap, prev, agreement: detector.simAgreement() };
});
const decisions = ctxs.reduce((s, c) => s + c.analyses.length, 0);

log('# Ghost Replay: validation results');
log();
log(`Generated by \`npm run validate\` on ${new Date().toISOString().slice(0, 10)}. Held-out synthetic matches (seeds ${SEEDS.join(', ')}), never used while tuning: **${decisions.toLocaleString('en-GB')} judged decisions**.`);
log();
log('> **What this does and doesn\'t show.** Every match is synthetic, so these tests show that the engine is *consistent with its own simulated world* and *behaves sensibly when the situation changes*. They do not show accuracy against real football, which would need real tracking data in the same format.');
log();

// ---- 1. calibration ---------------------------------------------------------------------
type Bin = { n: number; p: number; hit: number };
const bins = () => Array.from({ length: 10 }, (): Bin => ({ n: 0, p: 0, hit: 0 }));
function table(b: Bin[], what: string) {
  log(`| Predicted | Decisions | Mean predicted | Observed ${what} | Gap |`);
  log('| --- | --- | --- | --- | --- |');
  let ece = 0;
  const total = b.reduce((s, x) => s + x.n, 0);
  b.forEach((x, i) => {
    if (x.n < 10) return;
    const pred = x.p / x.n;
    const obs = x.hit / x.n;
    ece += (x.n / total) * Math.abs(pred - obs);
    log(`| ${i * 10}–${i * 10 + 10}% | ${x.n} | ${pct(pred)} | ${pct(obs)} | ${obs - pred >= 0 ? '+' : ''}${((obs - pred) * 100).toFixed(1)} pts |`);
  });
  return ece;
}

log('## 1. Calibration: do predicted chances match what happens?');
log();
log('### 1a. Pass completion (the passes players actually made)');
log();
log('Each pass the engine judged gets a predicted chance of coming off; we compare it with how often passes in that range really did come off in the match.');
log();
const passBins = bins();
let brier = 0;
let passes = 0;
for (const c of ctxs)
  for (const a of c.analyses) {
    if (a.event.type !== 'pass') continue;
    const ok = a.event.outcome === 'success' ? 1 : 0;
    const p = a.actual.pSuccess;
    const b = passBins[Math.min(9, Math.floor(p * 10))]!;
    b.n += 1;
    b.p += p;
    b.hit += ok;
    brier += (p - ok) ** 2;
    passes += 1;
  }
const passEce = table(passBins, 'completion');
log();
log(`**${passes.toLocaleString('en-GB')} passes. Expected calibration error ${pct(passEce)}; Brier score ${(brier / passes).toFixed(3)}.** (Bins with fewer than 10 passes are left out.)`);
log();
log('The pass model is calibrated with Platt scaling fitted on **training** matches only (seeds 1–12, `npm run fit-calibration -w @ghost/engine`), so these held-out numbers are a fair test of it.');
log();

log('### 1b. Reactive simulation against the model (options not taken)');
log();
log('For alternative passes the player did *not* play, the model\'s chance is compared with how often the pass comes off when the 50-run simulation plays it with defenders reacting.');
log();
const simBins = bins();
let sampled = 0;
for (const c of ctxs) {
  let k = 0;
  for (const a of c.analyses) {
    if (k++ % 40 !== 0) continue; // a spread sample through each match
    const o = a.alternatives.find((x) => x.action === 'pass' && !x.offside);
    if (!o) continue;
    const s = simulateWhatIf(c.match.meta, a.event, o, { rollouts: 20 }).summary;
    const b = simBins[Math.min(9, Math.floor(o.pSuccess * 10))]!;
    b.n += 1;
    b.p += o.pSuccess;
    b.hit += s.pSuccess;
    sampled += 1;
  }
}
const simEce = table(simBins, 'success in simulation');
log();
log(`**${sampled} options, 20 runs each. Expected calibration error ${pct(simEce)}.** The simulation is a separate physical model (reaction time, acceleration, reach, a race for the ball), so this checks the two agree; both are still models.`);
log();
log('**Reading this:** for confident options (80%+) the two agree within a few points. In the middle range the simulation is noticeably *stricter* than the model: its race for the ball at the receiver favours defenders more than real match outcomes do. That makes the simulation check conservative: a better option has to clear a harder bar to be shown. Closing this gap is listed under Known gaps.');
log();

// ---- 2. counterfactual robustness --------------------------------------------------------
log('## 2. Counterfactual robustness: change one thing, does the verdict move sensibly?');
log();
log('For every flagged moment whose better option is a pass, we change one thing in the freeze frame (or the players), keep everything else fixed, and re-judge.');
log();

type Probe = { name: string; expect: string; pass: number; same: number; total: number };
const probes: Record<string, Probe> = {
  closer: { name: 'Move the defender nearest to where the ball arrives 2 m closer to that spot', expect: 'chance of the pass coming off goes down', pass: 0, same: 0, total: 0 },
  away: { name: 'Move that defender 4 m further from the spot', expect: 'chance goes up (or stays, if the spot was already free)', pass: 0, same: 0, total: 0 },
  lane: { name: 'Put a defender in the middle of the passing lane', expect: 'chance goes down', pass: 0, same: 0, total: 0 },
  rank: { name: 'Defender moved closer: does the option lose value against the others?', expect: 'its lead over the next-best option shrinks', pass: 0, same: 0, total: 0 },
  pace: { name: 'Same pass simulated against slow vs fast defenders (pace 20 vs 95)', expect: 'it comes off at least as often against slow defenders', pass: 0, same: 0, total: 0 },
};

const sameOption = (a: GhostAnalysis | null, g: GhostOption) => (a ? [a.actual, ...a.alternatives].find((o) => o.action === g.action && o.targetPlayerId === g.targetPlayerId) : undefined);
const moveToward = (p: { x: number; y: number }, to: { x: number; y: number }, m: number) => {
  const d = dist(p, to) || 1;
  const k = Math.min(m, Math.max(0, d - 0.8)) / d;
  return { x: p.x + (to.x - p.x) * k, y: p.y + (to.y - p.y) * k };
};
function withPace(meta: MatchMeta, team: 'home' | 'away', pace: number): MatchMeta {
  return { ...meta, [team]: { ...meta[team], players: meta[team].players.map((p) => ({ ...p, attrs: { ...p.attrs, pace } })) } };
}

for (const c of ctxs) {
  const roster = buildRoster(c.match.meta);
  for (const m of [...c.live, ...c.recap].filter((x) => x.kind === 'miss' && x.ghost.action === 'pass' && x.ghost.targetPlayerId)) {
    const e = c.match.events.find((x) => x.id === m.eventId)!;
    const prev = c.prev.get(e.id);
    const base = analyzeEvent(e, roster, prev);
    const g0 = sameOption(base, m.ghost);
    if (!base || !g0) continue;
    // The spot where the ball arrives (a runner gets it ahead of them), and the defender nearest to it.
    const spot = g0.end;
    const opp = e.freezeFrame.filter((s) => s.team !== e.team && !roster.get(s.playerId)?.isGK);
    const marker = [...opp].sort((a, b) => dist(a.pos, spot) - dist(b.pos, spot))[0]!;
    const rejudge = (move: (s: (typeof e.freezeFrame)[number]) => { x: number; y: number }) => {
      const e2: MatchEvent = { ...e, freezeFrame: e.freezeFrame.map((s) => ({ ...s, pos: move(s) })) };
      const a2 = analyzeEvent(e2, roster, prev);
      return { a2, g: sameOption(a2, m.ghost) };
    };
    // closer
    const closer = rejudge((s) => (s.playerId === marker.playerId ? moveToward(s.pos, spot, 2) : s.pos));
    if (closer.g) {
      probes.closer!.total += 1;
      if (closer.g.pSuccess < g0.pSuccess - 1e-6) probes.closer!.pass += 1;
      else if (Math.abs(closer.g.pSuccess - g0.pSuccess) < 1e-6) probes.closer!.same += 1;
      // ranking: lead over the best *other* option
      const lead = (a: GhostAnalysis, g: GhostOption) => g.expectedValue - Math.max(...[a.actual, ...a.alternatives].filter((o) => o !== g).map((o) => o.expectedValue));
      probes.rank!.total += 1;
      if (lead(closer.a2!, closer.g) < lead(base, g0) - 1e-9) probes.rank!.pass += 1;
    }
    // away
    const away = rejudge((s) => (s.playerId === marker.playerId ? moveToward(s.pos, { x: s.pos.x * 2 - spot.x, y: s.pos.y * 2 - spot.y }, 4) : s.pos));
    if (away.g) {
      probes.away!.total += 1;
      if (away.g.pSuccess > g0.pSuccess + 1e-6) probes.away!.pass += 1;
      else if (Math.abs(away.g.pSuccess - g0.pSuccess) < 1e-6) probes.away!.same += 1;
    }
    // lane blocker: the second-nearest defender to the spot steps into the lane
    const blocker = [...opp].sort((a, b) => dist(a.pos, spot) - dist(b.pos, spot))[1];
    if (blocker) {
      const mid = { x: (e.start.x + m.ghost.end.x) / 2, y: (e.start.y + m.ghost.end.y) / 2 };
      const lane = rejudge((s) => (s.playerId === blocker.playerId ? mid : s.pos));
      if (lane.g) {
        probes.lane!.total += 1;
        if (lane.g.pSuccess < g0.pSuccess - 1e-6) probes.lane!.pass += 1;
        else if (Math.abs(lane.g.pSuccess - g0.pSuccess) < 1e-6) probes.lane!.same += 1;
      }
    }
    // pace in simulation
    const def = e.team === 'home' ? 'away' : 'home';
    const slow = simulateWhatIf(withPace(c.match.meta, def, 0.2), e, g0, { rollouts: 30 }).summary.pSuccess;
    const fast = simulateWhatIf(withPace(c.match.meta, def, 0.95), e, g0, { rollouts: 30 }).summary.pSuccess;
    probes.pace!.total += 1;
    if (slow > fast) probes.pace!.pass += 1;
    else if (slow === fast) probes.pace!.same += 1;
  }
}
log('| Change | Expected | Moved as expected | Unchanged | Moved the wrong way |');
log('| --- | --- | --- | --- | --- |');
for (const p of Object.values(probes)) {
  const wrong = p.total - p.pass - p.same;
  log(`| ${p.name} | ${p.expect} | ${p.pass} of ${p.total} (${pct(p.pass / Math.max(1, p.total))}) | ${p.same} | ${wrong} |`);
}
log();
log('"Unchanged" is expected when the change can\'t matter: a receiver already 5 m+ from everyone can\'t get freer, and a defender too far from a pass can\'t reach it whatever their pace.');
log();

// ---- 3. explanation correctness ----------------------------------------------------------
log('## 3. Explanation correctness: does the evidence checker catch false claims?');
log();
log('For every moment (live and recap), the checker gets the engine\'s fact sheet plus a deliberately false sentence of each kind below. A claim counts as **caught** if the checker reports a problem.');
log();
type Trap = { name: string; caught: number; total: number };
const traps: Record<string, Trap> = {
  number: { name: 'An invented percentage (one that appears nowhere in the facts)', caught: 0, total: 0 },
  distance: { name: 'A wrong distance (2.5 m off the real one)', caught: 0, total: 0 },
  player: { name: 'A player who isn\'t part of the moment', caught: 0, total: 0 },
  unmarked: { name: '"Unmarked" when a defender was under 3 m away', caught: 0, total: 0 },
  seen: { name: '"Could see" an option the facts say was outside the modeled view', caught: 0, total: 0 },
  offside: { name: 'An offside nobody was in', caught: 0, total: 0 },
  citation: { name: 'A claim citing a fact that doesn\'t exist', caught: 0, total: 0 },
};
let templatesOk = 0;
let templates = 0;
let exampleShown = false;
for (const c of ctxs) {
  const roster = buildRoster(c.match.meta);
  for (const m of [...new Map([...c.live, ...c.recap].map((x) => [x.eventId, x])).values()]) {
    const e = c.match.events.find((x) => x.id === m.eventId)!;
    const facts = momentFacts(m, e, roster);
    const factText = facts.map((f) => f.text).join('\n');
    const t = templateExplanation(m, facts, roster);
    templates += 1;
    if (!checkAgainstFacts(t.explanation, t.claims, facts, roster).length) templatesOk += 1;
    const check = (key: keyof typeof traps, sentence: string, claims: { text: string; facts: string[] }[] | null = null) => {
      traps[key]!.total += 1;
      const problems = checkAgainstFacts(sentence, claims, facts, roster);
      if (problems.length) traps[key]!.caught += 1;
      return problems;
    };
    const target = m.ghost.targetPlayerId ? roster.get(m.ghost.targetPlayerId)!.info.shortName : undefined;
    const who = roster.get(m.playerId)!.info.shortName;
    const used = numbersIn(factText);
    const absent = [97, 93, 89, 86, 79, 71, 67, 61, 57, 47].find((x) => !used.some((y) => Math.abs(y - x) <= 1))!;
    check('number', `${who} had a ${absent}% chance to find a teammate.`);
    const near = target ? factText.match(new RegExp(`Nearest defender to ${target}: [^,]+, ([\\d.]+) m away`)) : null;
    if (near) check('distance', `The nearest defender to ${target} was ${(Number(near[1]) + 2.5).toFixed(1)} m away.`);
    const stranger = [...roster.values()].find((r) => !factText.includes(r.info.shortName) && !factText.includes(r.info.name));
    if (stranger) check('player', `${stranger.info.shortName} was the obvious outlet.`);
    if (target && near && Number(near[1]) < 3) {
      const problems = check('unmarked', `${target} was completely unmarked.`);
      if (!exampleShown && problems.length) {
        exampleShown = true;
        log(`**Example.** Fact: *"${facts.find((f) => f.text.startsWith(`Nearest defender to ${target}`))!.text}"* False claim: *"${target} was completely unmarked."* Checker: *"${problems[0]}"*`);
        log();
      }
    }
    // Headline options are never outside the modeled view, so test the rule on a copy of the fact
    // sheet where the target's visibility fact says it was.
    if (target) {
      const altered = facts.map((f) => (f.text.startsWith(`${target} was `) && / for /.test(f.text) ? { ...f, text: `${target} was outside their modeled field of view (behind them) for ${who}.` } : f));
      if (altered.some((f, i) => f !== facts[i])) {
        traps.seen!.total += 1;
        if (checkAgainstFacts(`${who} could see ${target} clearly.`, null, altered, roster).length) traps.seen!.caught += 1;
      }
    }
    if (!/offside position/.test(factText) && target) check('offside', `${target} was offside, so the pass was never on.`);
    check('citation', `${who} made the wrong call.`, [{ text: `${who} made the wrong call.`, facts: ['F999'] }]);
  }
}
log('| False claim | Caught |');
log('| --- | --- |');
for (const t of Object.values(traps)) if (t.total) log(`| ${t.name} | ${t.caught} of ${t.total} (${pct(t.caught / t.total)}) |`);
log();
log(`**Explanations written from the facts pass the same check ${templatesOk} of ${templates} times (${pct(templatesOk / Math.max(1, templates))})**, so the checker doesn't reject true statements built from the facts.`);
log();

// ---- 4. the simulation check ------------------------------------------------------------
log('## 4. The simulation check: how often does it uphold the model?');
log();
const checked = ctxs.reduce((s, c) => s + c.agreement.checked, 0);
const agreed = ctxs.reduce((s, c) => s + c.agreement.agreed, 0);
log('**Definition.** A moment is *flagged* when the model\'s estimate of value left on the table passes the detector\'s bar (and the rate limits allow it). It is *upheld* when the 50-run simulation, with defenders reacting, finds that one of the top three fair alternatives creates at least 0.004 more expected goals per attempt than the choice the player made. If no alternative does, the moment is dropped: the simulation decides the model\'s estimate wasn\'t backed up, which is **not** proof that the player was right, only that the gain isn\'t clear.');
log();
log(`**Result: ${agreed} of ${checked} flagged moments upheld (${pct(agreed / Math.max(1, checked))}); ${checked - agreed} dropped before they reached the screen.**`);
log();
const ex = ctxs[0]!.live.find((m) => m.kind === 'miss' && m.sim);
if (ex) {
  const roster = buildRoster(ctxs[0]!.match.meta);
  const nm = (id?: string) => (id ? roster.get(id)!.info.shortName : '');
  log(`**Example (seed ${SEEDS[0]}, minute ${Math.floor(ex.clockMs / 60000) + 1}).** ${nm(ex.playerId)} chose ${ex.actual.action === 'pass' ? `a pass to ${nm(ex.actual.targetPlayerId)}` : ex.actual.action}; the model flagged ${ex.ghost.action === 'pass' ? `a pass to ${nm(ex.ghost.targetPlayerId)}` : ex.ghost.action} as worth ${ex.evLost.toFixed(3)} more. In 50 runs it created ${ex.sim!.ghost.toFixed(3)} expected goals per attempt against ${ex.sim!.actual.toFixed(3)}, so it was upheld (confidence: ${ex.confidence?.level === 'clear' ? 'high' : ex.confidence?.level === 'likely' ? 'medium' : 'low'}).`);
  log();
}

log('## Known gaps');
log();
log(`- **Model vs simulation in the middle range.** Options the model rates 35–80% come off less often in the reactive simulation (see 1b). The simulation is conservative, so this can only drop moments, never invent them, but the two models aren't yet reconciled.`);
log(`- **Wrong distances.** The checker caught ${traps.distance!.caught} of ${traps.distance!.total}. It ties a distance to the player named in the sentence and allows 0.5 m for rounding, so a wrong number that happens to match another distance about the same player gets through.`);
log('- **Synthetic world.** Calibration is against outcomes in simulated matches. Real-world accuracy needs real tracking data in the same shape; the models are built to take it.');
log('- **Modeled vision.** Visibility is a geometric estimate of field of view from movement and the last pass, not a measure of where the player actually looked. With no movement information it is labelled *unknown* rather than guessed.');
log();
log('## How to reproduce');
log();
log('```bash');
log('npm install');
log('npm run validate   # about a minute; rewrites this file');
log('npm test           # the automated test suite');
log('```');
log();
log(`Run time for this report: ${((performance.now() - t0) / 1000).toFixed(0)} s.`);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${lines.join('\n')}\n`);
console.error(`\nwrote ${OUT}`);
