// Regenerates src/data/profiles.ts (synthetic squads: names, ratings, two seasons of stats).
// Usage: npm run profiles -w @ghost/engine
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { synthesizeSquad } from '../src/data/synthesize';
import { CLUBS } from '../src/sim/teams';

const squads = Object.fromEntries(CLUBS.map((c) => [c.id, synthesizeSquad(c.id)]));
const out = `// GENERATED by scripts/make-profiles.ts. Do not edit by hand.
//
// Synthetic player profiles: invented names, ratings (0..1) and season stats.
// No real players or real Premier League data. To use a real league instead, replace this
// file with the same shape (club id -> PlayerProfile[] covering the formation's roles).

import type { PlayerProfile } from '../types';

export const PLAYER_PROFILES: Record<string, PlayerProfile[]> = ${JSON.stringify(squads, null, 2)};
`;
const path = fileURLToPath(new URL('../src/data/profiles.ts', import.meta.url));
writeFileSync(path, out);
console.log(`wrote ${path}: ${CLUBS.length} clubs, ${Object.values(squads).flat().length} players`);
